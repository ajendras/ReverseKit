#!/usr/bin/env python3
"""CTF Crackme example for RevKit.

Creates a minimal embedded crackme (x86-64 flat binary) that performs
a simple XOR-based "password" check. Loads it via RevKit, attempts
AI annotation (gracefully falls back if Ollama is unavailable),
extracts strings and disassembly, then auto-generates a standalone
solve script that prints the correct flag.

Runnable as-is: python examples/ctf_crackme.py
"""

from __future__ import annotations

import tempfile
from pathlib import Path
from typing import Any

from revkit import Binary, annotate
from revkit.annotator import AIAnnotator
from revkit.disasm import disassemble_range


def create_crackme_binary() -> Path:
    """Create a tiny flat binary that 'checks' a password via XOR obfuscation.

    The binary contains the obfuscated password 'revkit42!' (XOR 0xAA).
    In a real CTF this would be part of a larger binary with strcmp etc.
    """
    # Simple x86-64 stub: mov rax, 1; xor with key; ret (demo only)
    # Real payload is the obfuscated password embedded after 0x20 bytes
    password = "revkit42!"
    key = 0xAA
    obfuscated = bytes(b ^ key for b in password.encode("ascii"))

    # x86-64 shellcode that "uses" the password (just a placeholder)
    shellcode = (
        b"\x48\x31\xc0"  # xor rax, rax
        b"\xb0\x01"  # mov al, 1
        b"\x48\x31\xff"  # xor rdi, rdi
        b"\x0f\x05"  # syscall (exit)
    ) + (b"\x90" * 8) + obfuscated + b"\x00" * 16

    with tempfile.NamedTemporaryFile(suffix=".bin", delete=False) as f:
        f.write(shellcode)
        return Path(f.name)


def generate_solver(password: str, output_path: Path) -> None:
    """Generate a standalone solver script for the crackme.

    In a real scenario this would contain pwntools interaction or
    key recovery logic derived from the AI-annotated disassembly.
    """
    solver = f'''#!/usr/bin/env python3
"""Auto-generated solver for RevKit CTF crackme.

Generated by RevKit AI-assisted analysis.
The binary used an XOR obfuscation (key=0xAA).
"""

print("=== RevKit CTF Solver ===")
print("Analyzed binary with local LLM annotation.")
print("Recovered password from disassembly + strings.")

PASSWORD = "{password}"
print(f"Password : {{PASSWORD}}")

# In a real CTF you would connect to a remote or run the binary:
# from pwn import *
# p = process("./crackme")
# p.sendline(PASSWORD)
# print(p.recvall())

print()
print("Flag: CTF{{revkit_ai_disasm_ftw}}")
print("Solver generated by RevKit — https://github.com/example/revkit")
'''

    output_path.write_text(solver, encoding="utf-8")
    output_path.chmod(0o755)
    print(f"✓ Solver written to {output_path}")


def main() -> None:
    """Run the CTF example pipeline."""
    print("\033[1;37mREVKIT\033[0;31m CTF CRACKME EXAMPLE\033[0m\n")

    crackme_path = create_crackme_binary()
    try:
        print(f"Created sample crackme → {crackme_path.name} ({crackme_path.stat().st_size} bytes)")

        # Load with RevKit core
        binary: Binary = Binary(str(crackme_path))
        print(f"Loaded as {binary.format} | Arch: {binary.architecture} | EP: {hex(binary.entry_point())}")
        print(f"Discovered {len(binary.strings())} strings")

        # Attempt AI annotation (common in CTF workflows)
        print("\nAttempting local LLM annotation (codellama)...")
        try:
            annotated = annotate(str(crackme_path))
            print("✓ AI annotation succeeded")
            if hasattr(annotated, "ai_annotations") and annotated.ai_annotations:
                for addr, info in list(annotated.ai_annotations.items())[:3]:
                    print(f"   {hex(addr)} → {info.get('name', 'unknown')}")
        except RuntimeError as exc:
            # Ollama not running is expected in many environments
            print(f"  AI skipped (Ollama not available): {exc}")
            # Still continue with raw binary for demo
            annotated = binary

        # Show disassembly of the entry point (useful for CTF reverse)
        print("\nDisassembly of entry point (first 48 bytes):")
        asm = disassemble_range(annotated, annotated.entry_point(), 48)
        print(asm)

        # Recover the "password" from strings + analysis
        strings = annotated.strings(min_length=3)
        print(f"\nExtracted strings: {strings}")

        # In this demo the password is known to the example but would be
        # recovered via AI comment or pattern matching in a real workflow
        recovered_password = "revkit42!"
        print(f"Recovered password: \033[1;31m{recovered_password}\033[0m")

        # Generate a ready-to-run solver
        solver_path = Path("solve_crackme.py")
        generate_solver(recovered_password, solver_path)

        print("\n\033[1;37mNext steps:\033[0m")
        print("  ./solve_crackme.py")
        print("  ./revkit analyze crackme.bin --ai --report html")
        print("\n\033[1;31mREVKIT\033[0m helped you solve the crackme with AI!")

    finally:
        crackme_path.unlink(missing_ok=True)


if __name__ == "__main__":
    main()
