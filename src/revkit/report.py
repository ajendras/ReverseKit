    def _html_findings(self, scan: dict[str, Any]) -> str:
        """Convert scanner results into HTML cards."""
        parts = []
        for key, items in scan.items():
            if key == "total_findings" or not isinstance(items, list) or not items:
                continue
            title = key.replace("_", " ").upper()
            parts.append(f'<h3 style="color:#ff0044;margin:20px 0 10px 0;">{title}</h3>')
            for item in items[:6]:
                name = item.get("name") or item.get("type", "finding")
                desc = item.get("description", str(item))
                parts.append(
                    f'<div class="finding"><strong>{name}</strong><br>{desc}</div>'
                )
        return "\n".join(parts) if parts else "<p style='color:#666;'>No findings detected.</p>"

    def _html_annotations(self, annotations: dict[int, dict[str, str]]) -> str:
        """Render AI annotations as styled cards."""
        if not annotations:
            return "<p style='color:#666;'>No AI annotations present. Re-run with <span class='mono'>--ai</span>.</p>"

        parts = ['<div style="display:grid;grid-template-columns:repeat(auto-fit,minmax(340px,1fr));gap:20px;">']
        for addr, info in list(annotations.items())[:4]:
            name = info.get("name", "function")
            comment = info.get("comment") or info.get("explanation", "")
            parts.append(f"""
                <div style="border:3px solid #ff0044;padding:20px;background:#000;">
                    <div style="color:#ff0044;font-weight:700;font-size:1.1rem;">{name}</div>
                    <div style="color:#aaa;font-size:0.85rem;margin:4px 0 12px 0;">@ {hex(addr)}</div>
                    <div style="line-height:1.5;">{comment}</div>
                </div>
            """)
        parts.append("</div>")
        return "\n".join(parts)


