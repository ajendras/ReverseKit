            'xmlns="http://www.w3.org/2000/svg" aria-labelledby="title desc" '
            'role="img">'
            '<title id="title">RevKit CFG Example</title>'
            '<desc id="desc">Control flow graph with entry, basic blocks and '
            'conditional branches</desc>'
            '<rect width="620" height="380" fill="#111111"/>'
            '<rect x="40" y="50" width="130" height="68" rx="12" fill="#ff0044" stroke="#222" stroke-width="6"/>'
            '<text x="58" y="82" font-family="monospace" font-size="15" fill="#111111" font-weight="700">ENTRY</text>'
            '<line x1="170" y1="84" x2="250" y2="84" stroke="#ffffff" stroke-width="4" marker-end="url(#arrow)"/>'
            '<rect x="270" y="30" width="150" height="68" rx="12" fill="#ff0044" stroke="#222" stroke-width="6"/>'
            '<text x="290" y="62" font-family="monospace" font-size="14" fill="#111111">validate_input</text>'
            '<line x1="420" y1="64" x2="490" y2="64" stroke="#ffffff" stroke-width="4" marker-end="url(#arrow)"/>'
            '<rect x="510" y="20" width="90" height="55" rx="12" fill="#ff0044" stroke="#222" stroke-width="6"/>'
